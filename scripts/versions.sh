#!/usr/bin/env bash
# Regenerates docs/versions.md from the tools installed on this machine.
set -euo pipefail

cd "$(dirname "$0")/.."

for tool in lsb_release git gh python3 pipx pre-commit gitleaks; do
  command -v "$tool" >/dev/null || { echo "missing: $tool" >&2; exit 1; }
done

row() { printf '| %s | %s | %s |\n' "$1" "$2" "$3"; }

{
  echo "# Tool versions"
  echo
  echo "Generated by scripts/versions.sh. Do not edit by hand."
  echo
  echo "| Tool | Version | Check with |"
  echo "| --- | --- | --- |"
  row "WSL" "$(wsl.exe --version 2>/dev/null | tr -d '\0\r' | head -n1 | awk '{print $NF}')" "wsl --version (PowerShell)"
  row "Ubuntu" "$(lsb_release -ds)" "lsb_release -ds"
  row "WSL kernel" "$(uname -r)" "uname -r"
  row "git" "$(git --version | cut -d' ' -f3)" "git --version"
  row "gh" "$(gh --version | head -n1 | cut -d' ' -f3)" "gh --version"
  row "Python (system)" "$(python3 --version | cut -d' ' -f2)" "python3 --version"
  row "pipx" "$(pipx --version)" "pipx --version"
  row "pre-commit" "$(pre-commit --version | cut -d' ' -f2)" "pre-commit --version"
  row "gitleaks" "$(gitleaks version)" "gitleaks version"
} > docs/versions.md

echo "wrote docs/versions.md"

